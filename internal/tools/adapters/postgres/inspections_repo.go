// groupInspectionItems buckets the fetched item rows by their inspection_id so
// the repository can attach them to the fetched inspections in one round-trip.
func groupInspectionItems(rows []InspectionItem) map[pgtype.UUID][]InspectionItem {
	grouped := make(map[pgtype.UUID][]InspectionItem, len(rows))
	for i := range rows {
		id := rows[i].InspectionID
		grouped[id] = append(grouped[id], rows[i])
	}
	return grouped
}

// reinstatementFromRow maps an sqlc reinstatement row to the domain value.
func reinstatementFromRow(row Reinstatement) *core.Reinstatement {
	return &core.Reinstatement{
		ID:        row.ID.String(),
		ToolID:    row.ToolID.String(),
		ActorID:   row.ActorID.String(),
		Reason:    row.Reason,
		CreatedAt: row.CreatedAt.Time,
	}
}

// inspectionNotesValue encodes the notes for the nullable text column: an empty
// note (the common case) stores SQL NULL, a non-empty one the text.
func inspectionNotesValue(notes string) pgtype.Text {
	if notes == "" {
		return pgtype.Text{}
	}
	return pgtype.Text{String: notes, Valid: true}
}

// parseIdempotencyKey parses the CLIENT-SUPPLIED idempotency key (Story 7.5,
// NFR-R1): the HTTP layer already validated the canonical UUID form, so a
// malformed key reaching the store is a defense-in-depth failure — surfaced as
// an internal error, NEVER the 404 sentinel (a key is not a tool id). The
// shared parse contract lives in platform/pguuid (Epic 4 retro item D1).
func parseIdempotencyKey(key string) (pgtype.UUID, error) {
	uid, err := pguuid.ParseOptional(key)
	if err != nil {
		return pgtype.UUID{}, fmt.Errorf("tools postgres: malformed idempotency key: %w", err)
	}
	return uid, nil
}

// inspectionFromRow maps an sqlc inspection row (+ its ordered snapshot items)
// to the domain value. A NULL notes column reads back as "".
func inspectionFromRow(row Inspection, itemRows []InspectionItem) *core.Inspection {
	return &core.Inspection{
		ID:             row.ID.String(),
		ToolID:         row.ToolID.String(),
		InspectorID:    row.InspectorID.String(),
		Mode:           row.Mode,
		OverallResult:  row.OverallResult,
		Notes:          row.Notes.String,
		IdempotencyKey: row.IdempotencyKey.String(),
		SubmittedAt:    row.SubmittedAt.Time,
		Items:          inspectionItemsFromRows(itemRows),
	}
}

// inspectionItemsFromRows maps the ordered snapshot rows to the domain items
// (already ordered by position — the SQL ORDER BY guarantees it).
func inspectionItemsFromRows(rows []InspectionItem) []core.InspectionItem {
	if len(rows) == 0 {
		return []core.InspectionItem{}
	}
	items := make([]core.InspectionItem, 0, len(rows))
	for _, row := range rows {
		items = append(items, core.InspectionItem{
			ID:           row.ID.String(),
			InspectionID: row.InspectionID.String(),
			ItemID:       row.ItemID.String(),
			Label:        row.Label,
			Position:     int(row.Position),
			Result:       row.Result,
		})
	}
	return items
}

// AnonymizeUserReferences rewrites every reference to a deleted user's account
// to the canonical core.DeletedUserID sentinel in ONE transaction (Story 3.4,
// FR-24/AD-8): `inspections.inspector_id` AND `reinstatements.actor_id` both
// flip, so a failed half-write never leaves mixed references. IDEMPOTENT: a
// user with no matching rows (never inspected/reinstated, or already
// anonymized) is a no-op — the UPDATEs affect zero rows without error. The
// sentinel is a fixed well-known uuid, deliberately absent from users, so the
// DisplayNameResolver seam renders "Deleted User" (the inspection
// history/status report stay fully intact, FR-18). A malformed user id maps to
// core.ErrToolNotFound.
func (r *Repository) AnonymizeUserReferences(ctx context.Context, userID string) error {
	uid, err := parseOptionalUUID(userID)
	if err != nil {
		return core.ErrToolNotFound
	}
	deleted, err := parseOptionalUUID(core.DeletedUserID)
	if err != nil {
		return err
	}

	tx, err := r.beginTx(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }() // no-op after Commit

	q := r.queries.WithTx(tx)
	if err := q.UpdateInspectionsInspector(ctx, UpdateInspectionsInspectorParams{
		InspectorID:   deleted,
		InspectorID_2: uid,
	}); err != nil {
		return err
	}
	if err := q.UpdateReinstatementsActor(ctx, UpdateReinstatementsActorParams{
		ActorID:   deleted,
		ActorID_2: uid,
	}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return err
	}
	return nil
}

